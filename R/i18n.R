trackr_t <- function(key, language = "en", ...) {
  language <- language %||% "en"
  if (!language %in% names(trackr_translations)) {
    language <- "en"
  }

  value <- trackr_translations[[language]][[key]] %||%
    trackr_translations$en[[key]] %||%
    key

  args <- list(...)
  if (length(args) > 0) {
    value <- do.call(sprintf, c(list(fmt = value), args))
  }

  value
}

trackr_tr <- function(language = "en") {
  force(language)
  function(key, ...) {
    selected <- if (is.function(language)) language() else language
    trackr_t(key, selected, ...)
  }
}

trackr_language_choices <- function(tr = trackr_tr()) {
  stats::setNames(c("en", "pt"), c(tr("language.en"), tr("language.pt")))
}
